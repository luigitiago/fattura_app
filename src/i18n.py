class I18n:
    """Tiny translation helper.

    Usage::

        tr = I18n("de")
        tr.t("inv.title")                     # "Rechnungen"
        tr.t("clients.saved", name="Mario")   # interpolates {name}
    """

    def __init__(self, lang: str = "de"):
        self.lang = lang if lang in TRANSLATIONS else "de"

    def set_language(self, lang: str) -> None:
        if lang in TRANSLATIONS:
            self.lang = lang

    def t(self, key: str, **kwargs) -> str:
        table = TRANSLATIONS.get(self.lang, {})
        text = table.get(key)
        if text is None:
            # fall back to German, then to the key itself
            text = TRANSLATIONS["de"].get(key, key)
        if kwargs:
            try:
                return text.format(**kwargs)
            except (KeyError, IndexError, ValueError):
                return text
        return text
